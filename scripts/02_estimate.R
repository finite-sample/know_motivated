respondents <- readRDS(file.path(build_dir, "respondents.rds"))
tasks <- readRDS(file.path(build_dir, "tasks.rds"))
samples <- make_exhibit_samples(respondents, tasks)
exhibits <- estimate_exhibits(samples)
write_table(exhibits$cells, "accuracy_cells")
write_table(exhibits$contrasts, "accuracy_contrasts")
replication <- readRDS(file.path(build_dir, "replication_respondents.rds"))
replication_exhibits <- estimate_exhibits(make_exhibit_samples(replication, build_tasks(replication)), method = "hc2")
write_table(replication_exhibits$cells, "replication_accuracy_cells")
write_table(replication_exhibits$contrasts, "replication_accuracy_contrasts")
ratings <- estimate_ratings(respondents)
write_table(ratings$cells, "rating_cells")
write_table(ratings$contrasts, "rating_contrasts")
