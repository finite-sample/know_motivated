read_result <- function(name) {
  readr::read_csv(file.path(table_dir, paste0(name, ".csv")), show_col_types = FALSE)
}
format_interval <- function(estimate, low, high, scale = 1) {
  sprintf("%.2f [%.2f, %.2f]", scale * estimate, scale * low, scale * high)
}
contrasts <- read_result("accuracy_contrasts") |>
  dplyr::filter(
    exhibit %in% c("figure_2", "figure_3", "figure_4"), inference == "primary",
    contrast == "interaction" | exhibit == "figure_3"
  ) |>
  dplyr::transmute(
    Exhibit = exhibit, Group = position_label, Contrast = contrast,
    `Estimate [95% CI], pp` = format_interval(estimate, conf_low, conf_high, 100),
    `Two-sided p` = sprintf("%.4f", p_two_sided), N = n
  )
comparison <- read_result("published_accuracy_comparison") |>
  dplyr::filter(exhibit %in% c("figure_4", "figure_si_7")) |>
  dplyr::transmute(
    Exhibit = exhibit, Group = position_label,
    Congenial = congenial, Incentive = incentive,
    `Published (%)` = published_pct, `Reproduced (%)` = round(reproduced_pct, 2),
    `Difference (pp)` = round(difference_pp, 2)
  )
ratings <- dplyr::bind_rows(
  read_result("rating_contrasts"),
  dplyr::mutate(read_result("rating_pooled_contrasts"), position_label = "Pooled")
) |>
  dplyr::filter(contrast == "interaction") |>
  dplyr::transmute(
    Group = position_label,
    `Rating interaction [95% CI]` = format_interval(estimate, conf_low, conf_high),
    `Two-sided p` = sprintf("%.4f", p_two_sided), N = n
  )
repairs <- read_result("rating_standard_error_repair") |>
  dplyr::transmute(
    Group = position_label, Condition = contrast, Estimate = round(estimate, 4),
    `Archived SE` = round(archived_std_error, 6), `Correct SE` = round(std_error, 6)
  )
worker_exclusion <- read_result("worker_exclusion_summary") |>
  dplyr::transmute(
    Outcome = outcome, Group = position_label,
    Sample = ifelse(specification == "full_sample", "Full", "Exclude repeated IDs"),
    `Interaction [95% CI]` = format_interval(estimate, conf_low, conf_high),
    `Two-sided p` = sprintf("%.4f", p_two_sided), N = n
  )
